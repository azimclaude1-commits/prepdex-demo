# Extracts SVG markup (text only) from unpacked @web3icons/core and simple-icons tarballs and writes src/core/logos.js.
# Usage: npm pack @web3icons/core simple-icons; untar into DIR/w3 and DIR/si; python3 -I scripts/logos.py DIR src/core/logos.js
import re, sys, json, urllib.parse
W3 = sys.argv[1] + '/w3/package/dist/svgs/'
SI = sys.argv[1] + '/si/package/'
OUT = sys.argv[2]

def w3(path):
    s = open(W3 + path, encoding='utf8').read()
    m = re.search(r"=\s*'(.*?)'\s*\n", s, re.S)
    svg = m.group(1).encode('utf8').decode('unicode_escape').encode('latin1').decode('utf8')
    svg = re.sub(r'\s*class="web3icons"', '', svg)
    svg = re.sub(r'>\s+<', '><', svg).strip()
    assert svg.startswith('<svg') and svg.endswith('</svg>'), path
    return svg

def uri(svg):
    return 'data:image/svg+xml,' + urllib.parse.quote(svg, safe=' =:/";,.-')

coins = {s: w3(f'tokens/background/{s}.svg.js') for s in ['BTC','ETH','SOL','BNB','XRP','DOGE','ADA','AVAX','LINK','TRX','DOT','ARB','USDT','USDC']}
coins['TON'] = w3('networks/background/ton.svg.js')
wallets = {k: w3(f'wallets/background/{k}.svg.js') for k in ['metamask','okx','coinbase','trust']}
chains = {'ethereum': w3('networks/background/ethereum.svg.js'), 'arbitrum': w3('networks/background/arbitrum-one.svg.js'), 'base': w3('networks/background/base.svg.js'), 'bsc': w3('networks/background/binance-smart-chain.svg.js')}

data = json.load(open(SI + 'data/simple-icons.json', encoding='utf8'))
hexes = {d['slug']: d['hex'] for d in data} if isinstance(data, list) else {}
def si(slug, color='#fff'):
    svg = open(SI + f'icons/{slug}.svg', encoding='utf8').read().strip()
    svg = svg.replace('<svg ', f'<svg fill="{color}" ', 1)
    return svg
social = {k: si(k) for k in ['x','telegram','discord','youtube']}
wallets['walletconnect'] = si('walletconnect', '#3B99FC')

lines = ['// Real brand logos as SVG data URIs. Coins/wallets/chains: @web3icons/core (MIT); social: simple-icons (CC0).',
         '// Generated by scripts/logos.py — do not edit by hand.']
for name, d in [('COIN_LOGOS', coins), ('WALLET_LOGOS', wallets), ('CHAIN_LOGOS', chains), ('SOCIAL_LOGOS', social)]:
    lines.append(f'export const {name} = {{')
    for k, v in d.items():
        lines.append(f'  {json.dumps(k)}: {json.dumps(uri(v))},')
    lines.append('};')
open(OUT, 'w').write('\n'.join(lines) + '\n')
print('ok', len(coins), len(wallets), len(chains), len(social))
