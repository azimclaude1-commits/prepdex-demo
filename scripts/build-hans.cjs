// Builds src/core/i18n-hans.js: Traditional Chinese source strings -> Simplified Chinese (mainland wording).
// Run through scripts/build-i18n.mjs.
const fs = require('fs');
const OpenCC = require('opencc-js');
const conv = OpenCC.Converter({ from: 'tw', to: 'cn' });
// Taiwan wording in the source -> mainland wording (applied after character conversion)
const PHRASES = [
  ['网路', '网络'], ['预设', '默认'], ['帐户', '账户'], ['到帐', '到账'], ['帐号', '账号'], ['帐', '账'], ['资讯', '信息'], ['支援', '支持'],
  ['登入', '登录'], ['即时', '实时'], ['透过', '通过'], ['软体', '软件'], ['连结', '链接'], ['搜寻', '搜索'], ['设定', '设置'], ['载入', '加载'],
  ['选单', '菜单'], ['QR 码', '二维码'], ['萤幕', '屏幕'], ['程式', '程序'], ['品质', '质量'], ['启用', '激活'], ['最佳化', '优化'],
  ['使用者条款', '用户协议'], ['伺服器', '服务器'], ['相容', '兼容'], ['管道', '渠道'], ['简讯', '短信'], ['信箱', '邮箱'], ['开启', '打开'],
  ['重新整理', '刷新'], ['数位资产', '数字资产'], ['数位货币', '数字货币'], ['兆美元', '万亿美元'], ['影片', '视频'],
];
const keys = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const out = {};
for (const k of keys) {
  let v = conv(k);
  for (const [a, b] of PHRASES) v = v.split(a).join(b);
  if (v !== k) out[k] = v;
}
fs.writeFileSync('src/core/i18n-hans.js', '// Generated by scripts/build-hans.cjs: Traditional source string -> Simplified Chinese.\nexport default ' + JSON.stringify(out) + ';\n');
console.log(Object.keys(out).length, 'simplified strings');
